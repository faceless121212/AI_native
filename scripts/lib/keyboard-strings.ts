// Turns locales/<lang>/keyboard.json into native string files for both keyboards
// (docs/architecture.md §9). Pure functions: the CLI writes the result, i18n-check compares it.
import path from 'node:path';

import {
  type FlatStrings,
  type Lang,
  LANGUAGES,
  loadNamespace,
  placeholders,
  pluralParts,
  SOURCE_LANG,
} from './locales.ts';

export const SWIFT_OUT = 'targets/keyboard/Core/Strings.generated.swift';
export const androidOut = (lang: Lang) =>
  `modules/replywise-ime/android/src/main/res/${lang === SOURCE_LANG ? 'values' : `values-${lang}`}/keyboard_strings.xml`;

const SWIFT_CASE: Record<Lang, string> = {
  en: 'englishUK',
  de: 'german',
  fr: 'french',
  es: 'spanish',
  it: 'italian',
};

type Entry =
  | { kind: 'plain'; key: string; values: Record<Lang, string> }
  | { kind: 'template'; key: string; params: string[]; values: Record<Lang, string> }
  | {
      kind: 'plural';
      key: string;
      params: string[];
      one: Record<Lang, string>;
      other: Record<Lang, string>;
    };

const HEADER =
  'GENERATED by scripts/gen-keyboard-strings.ts from locales/<lang>/keyboard.json. Do not edit; run `npm run gen:keyboard-strings`.';

/** "bar.noFullAccess" → "barNoFullAccess" */
export function swiftName(key: string): string {
  return key
    .split('.')
    .map((part, i) => (i === 0 ? part : part.charAt(0).toUpperCase() + part.slice(1)))
    .join('');
}

/** "tone.sayNoKindly" → "kb_tone_say_no_kindly" */
export function androidName(key: string): string {
  return `kb_${key
    .replace(/\./g, '_')
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .toLowerCase()}`;
}

export function swiftLiteral(text: string): string {
  return `"${text.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n')}"`;
}

/** Escapes text for an Android <string>, turning {{name}} into %n$s / %n$d (count is a number). */
export function androidText(text: string, paramOrder: string[]): string {
  let out = text
    .replace(/\\/g, '\\\\')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/'/g, "\\'")
    .replace(/"/g, '\\"')
    .replace(/\n/g, '\\n');
  // Android only un-escapes %% when the string is formatted with arguments.
  if (paramOrder.length > 0) out = out.replace(/%/g, '%%');
  if (/^[@?]/.test(out)) out = `\\${out}`;
  return out.replace(/\{\{\s*(\w+)\s*\}\}/g, (_, name: string) => {
    const index = paramOrder.indexOf(name);
    if (index < 0) throw new Error(`Unknown placeholder {{${name}}}`);
    return `%${index + 1}$${name === 'count' ? 'd' : 's'}`;
  });
}

const SWIFT_KEYWORDS = new Set(
  (
    'associatedtype class deinit enum extension fileprivate func import init inout internal let open ' +
    'operator private protocol public rethrows static struct subscript typealias var break case continue ' +
    'default defer do else fallthrough for guard if in repeat return switch where while as catch false is ' +
    'nil super self Self throw throws true try language fill forLanguage'
  ).split(' '),
);

/** Throws when key paths can't become valid, unique Swift and Android identifiers. */
export function validateIdentifiers(keys: string[]): void {
  const swift = new Map<string, string>();
  const android = new Map<string, string>();
  for (const key of keys) {
    for (const part of key.split('.')) {
      if (!/^[a-z][A-Za-z0-9]*$/.test(part)) {
        throw new Error(
          `keyboard.json key "${key}": each part must be lowerCamelCase letters and digits`,
        );
      }
    }
    const s = swiftName(key);
    if (SWIFT_KEYWORDS.has(s))
      throw new Error(`keyboard.json key "${key}" becomes the reserved Swift name "${s}"`);
    const a = androidName(key);
    for (const [map, name] of [
      [swift, s],
      [android, a],
    ] as const) {
      const other = map.get(name);
      if (other)
        throw new Error(`keyboard.json keys "${other}" and "${key}" both become "${name}"`);
      map.set(name, key);
    }
  }
}

export type BuildOptions = {
  /**
   * Draft mode (`npm run gen:keyboard-strings -- --allow-missing`): a key missing in a language
   * gets the English text and is listed in `missing`, so native code can use new keys before the
   * translations land. Never for release: `npm run i18n:check` still fails on every missing key.
   */
  allowMissing?: boolean;
  /** Filled with "lang:key" for every fallback used in draft mode. */
  missing?: string[];
};

export function buildEntries(
  byLang: Record<Lang, FlatStrings>,
  options: BuildOptions = {},
): Entry[] {
  const source = byLang[SOURCE_LANG];
  const valuesFor = (key: string) =>
    Object.fromEntries(
      LANGUAGES.map((lang) => {
        const value = byLang[lang].get(key);
        if (value === undefined) {
          const fallback = source.get(key);
          if (!options.allowMissing || fallback === undefined)
            throw new Error(`keyboard.json (${lang}) is missing "${key}"`);
          options.missing?.push(`${lang}:${key}`);
          return [lang, fallback];
        }
        return [lang, value];
      }),
    ) as Record<Lang, string>;

  const entries: Entry[] = [];
  const seenPlural = new Set<string>();
  for (const key of source.keys()) {
    const plural = pluralParts(key);
    if (plural) {
      if (seenPlural.has(plural.base)) continue;
      seenPlural.add(plural.base);
      const one = valuesFor(`${plural.base}_one`);
      const other = valuesFor(`${plural.base}_other`);
      // count is always the first argument (%1$d on Android, first label in Swift).
      const found = placeholders(`${one[SOURCE_LANG]} ${other[SOURCE_LANG]}`);
      const params = ['count', ...found.filter((p) => p !== 'count')];
      entries.push({ kind: 'plural', key: plural.base, params, one, other });
      continue;
    }
    const values = valuesFor(key);
    const params = placeholders(values[SOURCE_LANG]);
    entries.push(
      params.length ? { kind: 'template', key, params, values } : { kind: 'plain', key, values },
    );
  }
  validateIdentifiers(entries.map((e) => e.key));
  return entries;
}

function swiftParam(name: string): string {
  return name === 'count' ? 'count: Int' : `${name}: String`;
}

function swiftFillCall(template: string, params: string[]): string {
  const pairs = params.map((p) => `"${p}": ${p === 'count' ? 'String(count)' : p}`).join(', ');
  return `Self.fill(${template}, [${pairs}])`;
}

export function generateSwift(entries: Entry[]): string {
  const fields: string[] = [];
  const methods: string[] = [];
  for (const e of entries) {
    const name = swiftName(e.key);
    if (e.kind === 'plain') {
      fields.push(`    public let ${name}: String`);
    } else if (e.kind === 'template') {
      fields.push(`    let ${name}Template: String`);
      methods.push(
        `    public func ${name}(${e.params.map(swiftParam).join(', ')}) -> String {\n        ${swiftFillCall(`${name}Template`, e.params)}\n    }`,
      );
    } else {
      fields.push(`    let ${name}One: String`, `    let ${name}Other: String`);
      const params = e.params;
      methods.push(
        `    public func ${name}(${params.map(swiftParam).join(', ')}) -> String {\n        let template = language.isPluralOne(count) ? ${name}One : ${name}Other\n        return ${swiftFillCall('template', e.params)}\n    }`,
      );
    }
  }

  const instances = LANGUAGES.map((lang) => {
    const args: string[] = [`        language: .${SWIFT_CASE[lang]}`];
    for (const e of entries) {
      const name = swiftName(e.key);
      if (e.kind === 'plain') args.push(`        ${name}: ${swiftLiteral(e.values[lang])}`);
      else if (e.kind === 'template')
        args.push(`        ${name}Template: ${swiftLiteral(e.values[lang])}`);
      else
        args.push(
          `        ${name}One: ${swiftLiteral(e.one[lang])}`,
          `        ${name}Other: ${swiftLiteral(e.other[lang])}`,
        );
    }
    return `    public static let ${lang} = KeyboardStrings(\n${args.join(',\n')}\n    )`;
  });

  return `// ${HEADER}
// No UIKit import: this file is part of the SwiftPM Core target.

import Foundation

public struct KeyboardStrings: Sendable {
    public let language: SupportedLanguage
${fields.join('\n')}

${methods.join('\n\n')}

    /// Replaces {{name}} placeholders. Unknown placeholders are left as they are.
    static func fill(_ template: String, _ values: [String: String]) -> String {
        var result = template
        for (name, value) in values {
            result = result.replacingOccurrences(of: "{{\\(name)}}", with: value)
        }
        return result
    }
}

extension KeyboardStrings {
${instances.join('\n\n')}

    public static func forLanguage(_ language: SupportedLanguage) -> KeyboardStrings {
        switch language {
${LANGUAGES.map((lang) => `        case .${SWIFT_CASE[lang]}: return .${lang}`).join('\n')}
        }
    }
}

extension SupportedLanguage {
    /// CLDR "one" category for integers: French uses it for 0 and 1, the other four for 1 only.
    public func isPluralOne(_ count: Int) -> Bool {
        switch self {
        case .french: return count == 0 || count == 1
        default: return count == 1
        }
    }
}
`;
}

export function generateAndroid(entries: Entry[], lang: Lang): string {
  const lines: string[] = [];
  for (const e of entries) {
    const name = androidName(e.key);
    if (e.kind === 'plural') {
      lines.push(
        `    <plurals name="${name}">`,
        `        <item quantity="one">${androidText(e.one[lang], e.params)}</item>`,
        `        <item quantity="other">${androidText(e.other[lang], e.params)}</item>`,
        '    </plurals>',
      );
    } else {
      const params = e.kind === 'template' ? e.params : [];
      lines.push(`    <string name="${name}">${androidText(e.values[lang], params)}</string>`);
    }
  }
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- ${HEADER} -->
<resources>
${lines.join('\n')}
</resources>
`;
}

/** Every generated file: repo-relative path → contents. */
export function generateKeyboardStringFiles(
  root: string,
  options: BuildOptions = {},
): Map<string, string> {
  const byLang = Object.fromEntries(
    LANGUAGES.map((lang) => [lang, loadNamespace(root, lang, 'keyboard')]),
  ) as Record<Lang, FlatStrings>;
  const entries = buildEntries(byLang, options);
  const files = new Map<string, string>([[SWIFT_OUT, generateSwift(entries)]]);
  for (const lang of LANGUAGES) files.set(androidOut(lang), generateAndroid(entries, lang));
  return files;
}

export function outputPath(root: string, relative: string): string {
  return path.join(root, relative);
}
